/** APR print format — the UGC six-monthly progress report page. */

import { docTitle, field, finish, newDoc, para } from "./layout.ts";
import type { ReportView } from "./apiClient.ts";

export async function buildAprPdf(view: ReportView): Promise<Buffer> {
	const doc = newDoc();
	docTitle(doc, "Six-Monthly Progress Report (APR)", `Roll number ${view.scholar.roll_number}`);

	field(doc, "Scholar", view.scholar.scholar_name);
	field(doc, "Roll number", view.scholar.roll_number);
	field(doc, "Department", view.scholar.department);
	field(doc, "Supervisor", view.supervisor?.full_name ?? null);
	field(doc, "Admission date", view.scholar.admission_date);
	field(doc, "Stage", view.scholar.stage);
	field(doc, "Reporting period", `${view.report.period} ${view.report.report_year}`);
	field(doc, "State", view.report.state);
	field(doc, "Approved on", view.report.approved_on);

	doc.moveDown(0.5);
	doc.font("Helvetica-Bold").fontSize(11).text("Summary of work");
	doc.moveDown(0.3);
	para(doc, view.report.summary);

	if (view.report.supervisor_comment !== null) {
		doc.moveDown(0.5);
		doc.font("Helvetica-Bold").fontSize(11).text("Supervisor comment");
		doc.moveDown(0.3);
		para(doc, view.report.supervisor_comment);
	}

	doc.moveDown(2).fontSize(8).fillColor("#8a8a8a")
		.text(`Generated by PhD Tracker on ${new Date().toISOString().slice(0, 10)} — audit trail in the system of record.`);
	return finish(doc);
}