/** Print-like documents (DESIGN_SYSTEM.md §7): black on white, rules not shadows, readable
 *  when photocopied in grayscale. No claymorphism here. */
import PDFDocument from "pdfkit";
import type { RegisterView, ReportView } from "./api.ts";

const MILESTONES: Record<string, string> = {
  coursework: "Coursework",
  proposal_approval: "Proposal approval",
  rac_review: "RAC review",
  pre_synopsis: "Pre-synopsis",
  thesis_submission: "Thesis submission",
  viva: "Viva",
  degree_awarded: "Degree awarded",
};
const STATES: Record<string, string> = {
  draft: "Draft",
  in_review: "In review",
  sent_back: "Sent back",
  approved: "Approved",
};
const ACTIONS: Record<string, string> = {
  submit: "Submitted",
  resubmit: "Resubmitted",
  approve: "Approved",
  send_back: "Sent back",
};

const day = (iso: string | null) =>
  iso ? new Date(iso).toLocaleDateString("en-GB", { day: "2-digit", month: "short", year: "numeric" }) : "—";
const stamp = (iso: string) =>
  new Date(iso).toLocaleString("en-GB", { day: "2-digit", month: "short", year: "numeric", hour: "2-digit", minute: "2-digit" });

function toBuffer(doc: PDFKit.PDFDocument): Promise<Buffer> {
  return new Promise((resolve, reject) => {
    const chunks: Buffer[] = [];
    doc.on("data", (c: Buffer) => chunks.push(c));
    doc.on("end", () => resolve(Buffer.concat(chunks)));
    doc.on("error", reject);
    doc.end();
  });
}

function header(doc: PDFKit.PDFDocument, university: string, title: string, subtitle: string) {
  doc.font("Helvetica-Bold").fontSize(15).text(university, { align: "center" });
  doc.moveDown(0.2).font("Helvetica").fontSize(11).text(title, { align: "center" });
  doc.fontSize(9).fillColor("#444444").text(subtitle, { align: "center" }).fillColor("black");
  const y = doc.y + 8;
  doc.moveTo(doc.page.margins.left, y).lineTo(doc.page.width - doc.page.margins.right, y).lineWidth(0.8).stroke();
  doc.y = y + 12;
}

function footer(doc: PDFKit.PDFDocument, generatedBy: string, generatedAt: string) {
  const range = doc.bufferedPageRange();
  for (let i = range.start; i < range.start + range.count; i++) {
    doc.switchToPage(i);
    const bottom = doc.page.height - doc.page.margins.bottom + 18;
    const margin = doc.page.margins.bottom;
    doc.page.margins.bottom = 0; // writing below the margin would otherwise add a blank page
    doc.font("Helvetica").fontSize(8).fillColor("#555555")
      .text(`Generated by ${generatedBy} on ${stamp(generatedAt)} · Anveshan · Page ${i + 1} of ${range.count}`,
        doc.page.margins.left, bottom, { align: "center", width: doc.page.width - doc.page.margins.left - doc.page.margins.right, lineBreak: false })
      .fillColor("black");
    doc.page.margins.bottom = margin;
  }
}

function keyValues(doc: PDFKit.PDFDocument, rows: [string, string][]) {
  const left = doc.page.margins.left;
  for (const [k, v] of rows) {
    const y = doc.y;
    doc.font("Helvetica-Bold").fontSize(10).text(k, left, y, { width: 140 });
    doc.font("Helvetica").text(v, left + 150, y, { width: doc.page.width - left - 150 - doc.page.margins.right });
    doc.moveDown(0.35);
  }
  doc.x = left;
}

export async function reportPdf(v: ReportView): Promise<Buffer> {
  const doc = new PDFDocument({ size: "A4", margin: 56, bufferPages: true, info: { Title: `Progress report – ${v.scholar}` } });
  header(doc, v.university, "Six-monthly Progress Report",
    `${v.period.replace("-", "–")} ${v.report_year}${v.unit ? ` · ${v.unit}` : ""}`);
  if (v.state !== "approved") {
    doc.font("Helvetica-Bold").fontSize(10).fillColor("#666666")
      .text(`NOT APPROVED — current status: ${STATES[v.state]}`, { align: "center" }).fillColor("black").moveDown(0.6);
  }
  keyValues(doc, [
    ["Scholar", v.scholar],
    ["Roll number", v.roll_number],
    ["Supervisor", v.supervisor ?? "—"],
    ["Status", STATES[v.state] ?? v.state],
    ["Submitted", day(v.submitted_at)],
    ["Approved", day(v.approved_at)],
  ]);
  doc.moveDown(0.6).font("Helvetica-Bold").fontSize(11).text("Summary of progress");
  doc.moveDown(0.3).font("Helvetica").fontSize(10).text(v.summary, { align: "justify", lineGap: 2 });
  doc.moveDown(0.9).font("Helvetica-Bold").fontSize(11).text("Approval history");
  doc.moveDown(0.3).font("Helvetica").fontSize(10);
  if (v.history.length === 0) doc.text("Not submitted yet.");
  for (const h of v.history) {
    const where = h.step && h.action !== "submit" ? ` at ${h.step}` : "";
    const to = h.to ? ` (to ${h.to})` : "";
    doc.font("Helvetica-Bold").text(`${ACTIONS[h.action] ?? h.action}${where}${to}`, { continued: true })
      .font("Helvetica").text(` — ${h.actor}, ${stamp(h.at)}`);
    if (h.comment) doc.fillColor("#333333").text(`“${h.comment}”`, { indent: 14 }).fillColor("black");
    doc.moveDown(0.3);
  }
  footer(doc, v.generated_by, v.generated_at);
  return toBuffer(doc);
}

const REGISTER_COLUMNS: [string, number][] = [
  ["Scholar", 150], ["Roll no.", 105], ["Unit", 140], ["Milestone", 105],
  ["Body", 45], ["Resolution no.", 95], ["Date", 65], ["Decision", 60],
];

export async function registerPdf(v: RegisterView): Promise<Buffer> {
  const doc = new PDFDocument({ size: "A4", layout: "landscape", margin: 40, bufferPages: true, info: { Title: "RDC register" } });
  const filters = [v.unit, v.filters.milestone_type && MILESTONES[v.filters.milestone_type], v.filters.status]
    .filter(Boolean).join(" · ");
  header(doc, v.university, "Committee decisions register", filters || "All decisions you can see");
  const left = doc.page.margins.left;
  const drawHead = () => {
    let x = left;
    const top = doc.y;
    doc.font("Helvetica-Bold").fontSize(9);
    for (const [label, width] of REGISTER_COLUMNS) {
      doc.text(label, x, top, { width: width - 6, lineBreak: false });
      x += width;
    }
    const y = top + 14;
    doc.moveTo(left, y).lineTo(left + REGISTER_COLUMNS.reduce((s, [, w]) => s + w, 0), y).lineWidth(0.6).stroke();
    doc.y = y + 5;
  };
  drawHead();
  if (v.rows.length === 0) doc.font("Helvetica").fontSize(10).text("No records.", left, doc.y + 6);
  for (const r of v.rows) {
    const cells = [r.scholar, r.roll_number, r.unit, MILESTONES[r.milestone_type] ?? r.milestone_type,
      r.approval_body, r.resolution_number ?? "—", day(r.resolution_date), r.status];
    doc.font("Helvetica").fontSize(9);
    const height = Math.max(...cells.map((c, i) => doc.heightOfString(c, { width: REGISTER_COLUMNS[i]![1] - 6 })));
    if (doc.y + height > doc.page.height - doc.page.margins.bottom - 10) {
      doc.addPage();
      drawHead();
    }
    const y = doc.y;
    let x = left;
    cells.forEach((c, i) => {
      doc.text(c, x, y, { width: REGISTER_COLUMNS[i]![1] - 6 });
      x += REGISTER_COLUMNS[i]![1];
    });
    doc.y = y + height + 6;
  }
  footer(doc, v.generated_by, v.generated_at);
  return toBuffer(doc);
}

/** RFC 4180 quoting, plus a leading quote on cells a spreadsheet would treat as a formula
 *  (=, +, -, @, tab, CR) so an opened CSV can never execute anything. */
export function csvCell(value: string | null): string {
  let s = value ?? "";
  if (/^[=+\-@\t\r]/.test(s)) s = `'${s}`;
  return /[",\n\r]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
}

export function registerCsv(v: RegisterView): string {
  const head = ["Scholar", "Roll number", "Unit", "Milestone", "Approval body", "Resolution number", "Resolution date", "Decision", "Notes"];
  const lines = v.rows.map((r) =>
    [r.scholar, r.roll_number, r.unit, MILESTONES[r.milestone_type] ?? r.milestone_type, r.approval_body,
      r.resolution_number, r.resolution_date, r.status, r.notes].map(csvCell).join(","));
  return `\uFEFF${[head.join(","), ...lines].join("\r\n")}\r\n`; // BOM: Excel reads UTF-8 names correctly
}
